d = 34260
limit = 10**10
for x in range(d, limit + 1, d):
    s = str(x)
    if not s.startswith('521'):
        continue
    pos4 = s.find('4', 3)
    if pos4 == -1:
        continue
    pos33 = s.find('33', pos4 + 1)
    if pos33 == -1:
        continue
    print(x, x // d)
